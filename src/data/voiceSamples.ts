// 준수 본인이 직접 쓴 답변 표본 — 챗봇 말투의 기준.
//
// 왜: 시스템 프롬프트의 규칙은 "하지 말 것"을 줄일 뿐 말투를 만들어 주지 못한다. knowledge.ts는
// 일부러 명사형 사실만 담아서, 모델이 "준수가 실제로 어떻게 말하는지" 볼 곳이 없었다.
// 그 결과 답은 정확한데 FAQ처럼 읽혔다(2026-10 대화 로그 분석).
//
// 규칙:
// - 본인이 직접 쓴 문장만 넣는다. AI가 대신 쓰거나 다듬은 문장은 넣지 않는다 —
//   그러면 준수의 말투가 아니라 모델의 말투를 다시 먹이는 것이 된다.
// - 카톡 치듯 쓴 그대로. 오타·줄임말을 고치지 않는다.
// - 답에 담긴 내용은 사실로 취급된다(챗봇이 그대로 말할 수 있다). 공개하면 안 되는 건 넣지 않는다.
// - 고친 뒤에는 `npm run persona:eval -- <라벨> --base <이전 결과.json>`로 전후를 비교한다.

